<?php

namespace App\Console\Commands;

use App\Livewire\Dashboard;
use App\Models\Process;
use App\Models\User;
use Illuminate\Console\Command;
use Illuminate\Contracts\Http\Kernel;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\File;

/**
 * Builds a static, server-free copy of the dashboard into docs/ for GitHub Pages.
 *
 * It renders the real page once, removes everything that needs PHP/Livewire
 * (scripts, wire: attributes, logout and settings), and adds the process list
 * as JSON plus a small script for status sorting, paging and the menu.
 *
 * Run `npm run build` first, then: php artisan kronos:export-static
 */
class ExportStaticDemo extends Command
{
    protected $signature = 'kronos:export-static {--out=docs : Output folder, relative to the project root}';

    protected $description = 'Export a static demo of the dashboard (for GitHub Pages)';

    public function handle(Kernel $kernel): int
    {
        $out = base_path($this->option('out'));
        $manifest = public_path('build/manifest.json');

        if (! File::exists($manifest)) {
            $this->error('No built assets. Run `npm run build` first.');

            return self::FAILURE;
        }

        // Render as a throwaway demo user, so no real name ends up in the page.
        $demo = new User(['name' => 'Demo User', 'email' => 'demo@kronos.test']);
        $demo->email_verified_at = now();
        Auth::setUser($demo);

        $response = $kernel->handle(Request::create('/', 'GET'));

        if ($response->getStatusCode() !== 200) {
            $this->error('Rendering / failed with HTTP '.$response->getStatusCode());

            return self::FAILURE;
        }

        $html = $this->makeStatic($response->getContent());

        $css = collect(json_decode(File::get($manifest), true))
            ->firstWhere('src', 'resources/css/app.css')['file'];

        File::ensureDirectoryExists("$out/assets");
        File::copy(public_path("build/$css"), "$out/assets/app.css");
        File::put("$out/index.html", $html);
        File::put("$out/.nojekyll", ''); // serve files as-is on GitHub Pages

        $this->info("Static demo written to {$this->option('out')}/index.html");

        return self::SUCCESS;
    }

    private function makeStatic(string $html): string
    {
        $replacements = [
            // Scripts that need the server (Livewire, Flux, Vite JS, appearance).
            '#<script\b[^>]*>[\s\S]*?</script>#i' => '',
            '#<link[^>]+rel="modulepreload"[^>]*>#i' => '',
            // Livewire wiring.
            '#\s(?:wire:[\w.:-]+|wire:key)(?:="[^"]*")?#' => '',
            // Logout forms and the profile menu (settings / logout): no server to post to.
            '#<form method="POST" action="[^"]*logout"[\s\S]*?</form>#' => '',
            '#<ui-menu\b[\s\S]*?</ui-menu>#' => '',
            // Built CSS, and links back into the app.
            '#href="[^"]*/build/assets/[^"]+\.css"#' => 'href="assets/app.css"',
            '#href="https?://localhost[^"]*"#' => 'href="./"',
        ];

        $html = preg_replace(array_keys($replacements), array_values($replacements), $html);

        $head = <<<'HTML'
    <meta name="description" content="Kronos HR dashboard: static demo with sample data">
    <style>[x-cloak]{display:none!important} ui-table-scroll-area{display:block}</style>
    <script defer src="https://cdn.jsdelivr.net/npm/alpinejs@3.14.1/dist/cdn.min.js"></script>
HTML;

        $html = str_replace('</head>', $head."\n</head>", $html);
        $html = str_replace('</body>', $this->demoScript()."\n</body>", $html);

        return "<!-- Static demo generated by `php artisan kronos:export-static`. Do not edit by hand. -->\n".$html;
    }

    private function demoScript(): string
    {
        $rows = Process::query()
            ->with(['client:id,name', 'type:id,name', 'owner:id,name', 'state:id,name'])
            ->orderByDesc('internal_code')
            ->get()
            ->map(fn (Process $p) => [
                'code' => $p->internal_code,
                'client' => $p->client?->name,
                'type' => $p->type?->name,
                'owner' => $p->owner?->name,
                'date' => $p->preview_end_date?->format('Y-m-d'),
                'status' => $p->state?->name,
                'statusClass' => Dashboard::statusClass($p->state?->name),
            ]);

        $data = json_encode($rows, JSON_UNESCAPED_UNICODE | JSON_HEX_TAG);
        $perPage = Dashboard::PER_PAGE;
        $js = File::get(resource_path('js/static-demo.js'));

        return "<script>window.KRONOS_DEMO = {rows: $data, perPage: $perPage};</script>\n<script>\n$js</script>";
    }
}
