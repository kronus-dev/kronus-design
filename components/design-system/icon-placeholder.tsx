type IconPlaceholderProps = ComponentProps<"svg"> & {
  lucide: string;
  tabler?: string;
  hugeicons?: string;
  phosphor?: string;
  remixicon?: string;
  size?: number | string;
};

export function IconPlaceholder({ lucide, tabler, hugeicons, phosphor, remixicon, ...props }: IconPlaceholderProps) {
  void tabler; void hugeicons; void phosphor; void remixicon;
  const Icon = ICONS[lucide as keyof typeof ICONS] ?? CircleIcon;
  return <Icon {...props} />;
}